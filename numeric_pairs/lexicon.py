def build_address_starts() -> tuple[str, ...]:
    """Preserve key historical indices, combine gender-agreed places with varied street openings."""
    starts: list[str] = [
        "השליח הגיע לרחוב ",
        "הסניף נמצא ברחוב ",
    ]
    for item in ADDRESS_ARRIVAL_STARTS[1:]:
        starts.append(item)
    for place in STREET_PLACES_M:
        candidate = f"{place} נמצא ברחוב "
        if candidate not in starts:
            starts.append(candidate)
    for place in STREET_PLACES_F:
        starts.append(f"{place} נמצאת ברחוב ")
    for item in ADDRESS_VARIED_STARTS:
        starts.append(item)
    return tuple(starts)


ADDRESS_STARTS: tuple[str, ...] = build_address_starts()

